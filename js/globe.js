function inPoly(x, y, poly) {
  let ins = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi)) ins = !ins;
  }
  return ins;
}
const rad = d => d * Math.PI / 180;
const vec = (lon, lat) => [Math.cos(rad(lat)) * Math.cos(rad(lon)), Math.cos(rad(lat)) * Math.sin(rad(lon)), Math.sin(rad(lat))];

export function drawGlobe(svg, { from = [3.67, 51.55], to = [-48.72, -28.33], center = [-22, 12], R = 300, cx = 600, cy = 330 } = {}) {
  const [l0, p0] = center.map(rad);
  // projeção ortográfica centrada em (l0, p0)
  const proj = (lon, lat) => {
    const l = rad(lon), p = rad(lat);
    const cosc = Math.sin(p0) * Math.sin(p) + Math.cos(p0) * Math.cos(p) * Math.cos(l - l0);
    const x = R * Math.cos(p) * Math.sin(l - l0);
    const y = R * (Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(l - l0));
    return [cx + x, cy - y, cosc];
  };
  const NS = 'http://www.w3.org/2000/svg';
  const g = document.createElementNS(NS, 'g');
  let dots = '';
  for (let lat = -70; lat <= 82; lat += 2.2) {
    const step = 2.2 / Math.max(.2, Math.cos(rad(lat)));
    for (let lon = -180; lon < 180; lon += step) {
      const [x, y, c] = proj(lon, lat);
      if (c <= .05) continue;
      if (!LAND.some(poly => inPoly(lon, lat, poly))) continue;
      const r = (.9 + c * 1.5).toFixed(2);
      dots += `M${(x - +r).toFixed(1)} ${y.toFixed(1)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    }
  }
  // grade
  let grid = '';
  for (let lat = -60; lat <= 60; lat += 30) { let d = ''; for (let lon = -180; lon <= 180; lon += 3) { const [x, y, c] = proj(lon, lat); d += (c > 0 ? (d && d.at(-1) !== 'M' ? 'L' : 'M') + x.toFixed(1) + ' ' + y.toFixed(1) : ''); } grid += d; }
  for (let lon = -180; lon < 180; lon += 30) { let d = ''; for (let lat = -88; lat <= 88; lat += 3) { const [x, y, c] = proj(lon, lat); d += (c > 0 ? (d ? 'L' : 'M') + x.toFixed(1) + ' ' + y.toFixed(1) : ''); } grid += d; }
  // rota: arco de grande círculo, levantado do chão
  const a = vec(...from), b = vec(...to);
  const om = Math.acos(a[0] * b[0] + a[1] * b[1] + a[2] * b[2]);
  let route = '';
  for (let i = 0; i <= 80; i++) {
    const t = i / 80, s = Math.sin(om);
    const k1 = Math.sin((1 - t) * om) / s, k2 = Math.sin(t * om) / s;
    const v = [a[0] * k1 + b[0] * k2, a[1] * k1 + b[1] * k2, a[2] * k1 + b[2] * k2];
    const lat = Math.asin(v[2]) * 180 / Math.PI, lon = Math.atan2(v[1], v[0]) * 180 / Math.PI;
    const lift = 1 + .16 * Math.sin(Math.PI * t);
    const [x, y] = proj(lon, lat);
    const X = cx + (x - cx) * lift, Y = cy + (y - cy) * lift;
    route += (i ? 'L' : 'M') + X.toFixed(1) + ' ' + Y.toFixed(1);
  }
  const A = proj(...from), B = proj(...to);
  g.innerHTML = `
    <defs><radialGradient id="glb" cx="40%" cy="35%" r="70%"><stop offset="0" stop-color="#0f5872" stop-opacity=".55"/><stop offset="1" stop-color="#04121d" stop-opacity="0"/></radialGradient></defs>
    <circle cx="${cx}" cy="${cy}" r="${R}" fill="url(#glb)" stroke="rgba(234,245,242,.14)"/>
    <path d="${grid}" fill="none" stroke="rgba(234,245,242,.07)" stroke-width=".8"/>
    <path d="${dots}" fill="rgba(234,245,242,.42)"/>
    <path class="r-path" d="${route}" pathLength="1" data-routepath/>
    <circle cx="${A[0].toFixed(1)}" cy="${A[1].toFixed(1)}" r="5" fill="#E8CFA0"/>
    <circle cx="${B[0].toFixed(1)}" cy="${B[1].toFixed(1)}" r="7" fill="#6FF2DC"/><circle cx="${B[0].toFixed(1)}" cy="${B[1].toFixed(1)}" r="14" fill="none" stroke="#6FF2DC" opacity=".5"/>`;
  svg.appendChild(g);
  const vb = svg.viewBox.baseVal;
  return { from: [A[0] / vb.width, A[1] / vb.height], to: [B[0] / vb.width, B[1] / vb.height] };
}
